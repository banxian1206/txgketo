def split_erp_category(path: str) -> tuple[str, str]:
    """把 ERP 的 `一级->二级->三级` 路径拆成 (二级, 三级)。

    · 2 级（如 `车间/仓库耗材类->生产用品类`）→ (一级, 二级)
    · 4 级（如 `标准化类->通用零件->链轮->链轮`）→ (二级, 末级)
    """
    parts = [p for p in (path or "").split("->") if p]
    if len(parts) >= 4:
        return parts[1], parts[-1]
    if len(parts) == 3:
        return parts[1], parts[2]
    if len(parts) == 2:
        return parts[0], parts[1]
    if len(parts) == 1:
        return "其他", parts[0]
    return "(空)", "(空)"


def class_of(erp_category_path: str) -> tuple[str, str, str] | None:
    """ERP 分类路径 → (类别码, 品类码, 品类名)；映射表里没有就返回 None（调用方跳过并报账）。"""
    return CLASS_MAP.get(split_erp_category(erp_category_path))


def supplier_kind(erp_kind: str) -> str:
    """ERP 供应商分类 → 本系统 kind（认不出归「其他」）。"""
    return SUPPLIER_KIND_MAP.get((erp_kind or "").strip(), "其他")


